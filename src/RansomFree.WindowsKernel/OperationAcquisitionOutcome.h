#define SQ_ACQ_NO_ASSOCIATION 0u
#define SQ_ACQ_PREBIND_REFUSAL 1u
#define SQ_ACQ_COPY_PENDING 2u
#define SQ_ACQ_BOUND_COPY_FAILURE 3u
#define SQ_ACQ_BYTES_UNAVAILABLE 4u
