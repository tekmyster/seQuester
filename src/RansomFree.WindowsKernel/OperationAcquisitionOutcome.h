typedef struct _SQ_ACQUISITION_REQUEST {
    ULONG ProtocolVersion, Command;
    UUID Provider;
    ULONGLONG Epoch, Instance, Sequence;
} SQ_ACQUISITION_REQUEST;
typedef struct _SQ_ACQUISITION_CAPABILITIES {
    ULONG Version, Size;
    UUID Provider;
    ULONGLONG Epoch, Flags;
    ULONG OutcomeVersion, OutcomeSize;
} SQ_ACQUISITION_CAPABILITIES;
typedef struct _SQ_ACQUISITION_OUTCOME {
    ULONG Version, Size;
    UUID Provider;
    ULONGLONG Epoch, Instance, Sequence, ProcessGeneration;
    ULONGLONG NegativeAssociation, OriginCandidate, OriginGeneration, ObservedQpc;
    NTSTATUS NativeStatus;
    ULONG State, Stage, Certainty, Flags, Reserved0;
    ULONGLONG Reserved1, Reserved2;
} SQ_ACQUISITION_OUTCOME;
typedef struct _SQ_NEGATIVE_ACQUISITION_HEALTH {
    ULONG Version,Size;
    UUID Provider;
    ULONGLONG Epoch;
    ULONG Capacity,Live;
    ULONGLONG NextAssociation,ReferencesTaken,ReferencesReleased,GapCount,GapQpc,BindAttempted;
} SQ_NEGATIVE_ACQUISITION_HEALTH;
